export type Language = 'uk' | 'en';
export type TranslationKey = keyof typeof translations.uk;

interface LanguageContextProps {
  t: (key: TranslationKey) => string;
  language: Language;
}

export const LanguageContext = createContext<LanguageContextProps>({
  t: (key) => translations.uk[key],
  language: 'uk',
});

export const useTranslation = () => useContext(LanguageContext);

export const LanguageProvider: React.FC<{ language: Language, children: ReactNode }> = ({ language, children }) => {
  const t = (key: TranslationKey) => {
    return translations[language][key] || translations['uk'][key] || key;
  };

  return (
    <LanguageContext.Provider value={{ t, language }}>
      {children}
    </LanguageContext.Provider>
  );
};
